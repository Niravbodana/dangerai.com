export function getWikiTitlesForRecipe(recipe) {
  if (!recipe?.id) return [];
  const fromId = WIKI_TITLE_BY_ID[recipe.id] || [];
  const name = recipe.name || "";
  return [...new Set([...fromId, name, name.replace(/\s*\(.*\)/, "").trim()])].filter(Boolean);
}

export function getSimilarRecipeId(recipeId) {
  return SIMILAR_RECIPE_FALLBACK[recipeId] || null;
}
