export function buildIngredients(mainIngredient, style, isNonVeg = false) {
  const base = isNonVeg ? NONVEG_BASE : VEG_BASE;
  const extras = STYLE_EXTRAS[style] || STYLE_EXTRAS.Curry;
  const staples = COMMON_STAPLES.slice(0, 2);
  const all = [mainIngredient, ...base.slice(0, 3), ...extras.slice(0, 2), ...staples];

  const seen = new Set();
  return all.filter((ing) => {
    const key = ing.name.toLowerCase();
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
}

